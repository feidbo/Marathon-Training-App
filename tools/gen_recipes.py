#!/usr/bin/env python3
"""Generate core/.../RecipeData.kt from tools/foodhero_recipes.json.

foodhero_recipes.json holds recipes copied from Food Hero (Oregon State University Extension Service,
foodhero.org), a kitchen-tested recipe site: title, ingredient lines, directions and notes exactly as
published, and nutrition per serving transcribed from each recipe's Nutrition Facts label. The amount /
unit / item / dept fields are added for the shopping list (one per published ingredient line).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
recipes = json.loads((ROOT / "tools/foodhero_recipes.json").read_text())


def s(x):
    return '"' + str(x).replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def num(x):
    return "null" if x is None else f"{float(x)}"


out = [
    "// GENERATED by tools/gen_recipes.py from tools/foodhero_recipes.json (Food Hero, Oregon State University). Do not edit.",
    "package com.feidbo.marathon.core",
    "",
    "internal val foodHeroRecipes: Map<String, Recipe> = mapOf(",
]
for key, r in recipes.items():
    lab = r["label"]
    out.append(f"    {s(key)} to Recipe(")
    out.append(f"        id = {s(key)}, title = {s(r['title'])}, url = {s(r['url'])},")
    out.append(f"        makes = {s(r['makes'])}, prep = {s(r['prep'] or '')}, cook = {s(r['cook'] or '')},")
    out.append(f"        servings = {lab['servings']}, servingSize = {s(lab['size'])},")
    out.append(f"        perServing = Macros({float(lab['kcal'])}, {float(lab['protein'])}, {float(lab['carbs'])}, {float(lab['fat'])}),")
    out.append("        ingredients = listOf(")
    for i in r["ingredients"]:
        dept = "null" if i["dept"] is None else f"Dept.{i['dept']}"
        out.append(f"            RecipeIngredient({s(i['line'])}, {num(i['amount'])}, {s(i['unit'])}, {s(i['item'])}, {dept}),")
    out.append("        ),")
    out.append("        steps = listOf(" + ", ".join(s(x) for x in r["steps"]) + "),")
    out.append("        notes = listOf(" + ", ".join(s(x) for x in r["notes"]) + "),")
    out.append("    ),")
out.append(")")
(ROOT / "core/src/main/kotlin/com/feidbo/marathon/core/RecipeData.kt").write_text("\n".join(out) + "\n", encoding="utf-8")
