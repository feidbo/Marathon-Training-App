#!/usr/bin/env python3
"""Generate core/src/main/kotlin/.../PlanData.kt from docs/First_Marathon_Plan_Eugene_2027.md.

Run from the repository root:  python3 tools/gen_plan.py
"""
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs" / "First_Marathon_Plan_Eugene_2027.md"
OUT = ROOT / "core/src/main/kotlin/com/feidbo/marathon/core/PlanData.kt"

MONTHS = {"Oct": 10, "Nov": 11, "Dec": 12, "Jan": 1, "Feb": 2, "Mar": 3, "Apr": 4}
STRETCH = re.compile(r"\s*·\s*quad stretch 3 min( afterward)?\s*$")


def run_kind(text: str) -> str:
    t = text.lower()
    if t.startswith("rest"):
        return "REST"
    if "no run" in t:
        return "NONE"
    if "eugene marathon" in t:
        return "RACE"
    if "half marathon race" in t:
        return "HALF_RACE"
    if "marathon pace" in t:
        return "MARATHON_PACE"
    if "tempo" in t:
        return "TEMPO"
    if "uphill hard" in t:
        return "HILLS"
    if "fartlek" in t:
        return "FARTLEK"
    if "recovery" in t:
        return "RECOVERY"
    if "long run" in t or "dress rehearsal" in t:
        return "LONG"
    if "shakeout" in t:
        return "SHAKEOUT"
    if "strides" in t:
        return "EASY_STRIDES"
    return "EASY"


def strength_kind(text: str, d: date) -> str:
    t = text.lower()
    if "learn the machines" in t:
        return "LEARN"
    if "strength" not in t or "no strength" in t:
        return "NONE"
    if "light" in t:
        return "LIGHT"
    if d < date(2026, 12, 14):
        return "PHASE1"
    if d < date(2027, 2, 8):
        return "PHASE2"
    return "PHASE3"


def mp_miles(text: str) -> float:
    t = text.lower()
    if "marathon pace" not in t:
        return 0.0
    m = re.search(r"(?:last\s+)?(\d+(?:\.\d+)?)\s*(?:mi\s+)?at marathon pace", t)
    return float(m.group(1)) if m else 0.0


def kt_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def main() -> None:
    lines = SRC.read_text(encoding="utf-8").splitlines()
    week = None
    week_note = ""
    expect_note = False
    days = []
    for line in lines:
        m = re.match(r"^### Week (\d+) ·", line)
        if m:
            week = int(m.group(1))
            week_note = ""
            expect_note = True
            continue
        if line.startswith("## ") or line.startswith("### Race-day"):
            week = None if not line.startswith("### Week") else week
        if week is None:
            continue
        if expect_note and line.strip() and not line.startswith("|"):
            week_note = line.strip()
            if week_note.endswith(":"):  # Week 20 points at a table; the app shows that table itself.
                week_note = "Lighter week and checkpoint. Your Mar 7 half sets marathon pace for the rest of the plan."
            expect_note = False
            continue
        if line.startswith("| Date") or line.startswith("| ---"):
            expect_note = False
            continue
        m = re.match(r"^\| (\w{3}) (\w{3}) (\d+) · (Day \d+|Race) \| (.+?) \| (.+?) \|$", line)
        if not m:
            continue
        _, mon, dd, label, text, mi = m.groups()
        month = MONTHS[mon]
        d = date(2026 if month >= 10 else 2027, month, int(dd))
        text = STRETCH.sub("", text).strip()
        miles = 0.0 if mi.strip() in ("—", "-") else float(mi)
        days.append(dict(date=d, week=week, label=label, text=text, miles=miles,
                         run=run_kind(text), strength=strength_kind(text, d),
                         mp=mp_miles(text), note=week_note))

    # Sanity checks against the plan's own numbers.
    assert len(days) == 192, len(days)
    assert days[0]["date"] == date(2026, 10, 16)
    assert days[-1]["date"] == date(2027, 4, 25) and days[-1]["run"] == "RACE"
    for a, b in zip(days, days[1:]):
        assert (b["date"] - a["date"]).days == 1, (a, b)

    out = []
    out.append("// GENERATED by tools/gen_plan.py from docs/First_Marathon_Plan_Eugene_2027.md. Do not edit.")
    out.append("package com.feidbo.marathon.core")
    out.append("")
    out.append("import java.time.LocalDate")
    out.append("")
    out.append("internal val planDays: List<PlannedDay> = listOf(")
    for i, d in enumerate(days):
        dt = d["date"]
        out.append(
            f"    PlannedDay({i}, LocalDate.of({dt.year}, {dt.month}, {dt.day}), {d['week']}, "
            f"{kt_str(d['label'])}, {kt_str(d['text'])}, {d['miles']}, RunKind.{d['run']}, "
            f"StrengthKind.{d['strength']}, {d['mp']}, {kt_str(d['note'])}),"
        )
    out.append(")")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {len(days)} days to {OUT.relative_to(ROOT)}", file=sys.stderr)


if __name__ == "__main__":
    main()
